package com.donnations.backend.http.dto

import java.time.Instant
import java.util.UUID

data class DonationRequestDto(
    val donationId: UUID, // generated by the client once per donate attempt and reused on every retry (idempotency key).
    val amount: String, // decimal string in major units ("25.00") in the campaign's currency.
)

data class DonationDto(
    val id: UUID,
    val campaignId: UUID,
    val currency: String,
    val amount: String, // decimal string in major units ("25.00").
    val status: String, // PENDING -> PROCESSING -> COMPLETED or FAILED.
    val failureCode: String?, // ErrorCode value when FAILED.
    val createdAt: Instant,
    val processedAt: Instant?,
)

data class DonationOptionsDto(
    val campaignId: UUID,
    val campaignTitle: String,
    val currency: String,
    val acceptingDonations: Boolean, // false once the campaign has ended; suggestedAmounts is then empty.
    val suggestedAmounts: List<String>, // decimal strings in major units ("25.00") in the campaign's currency.
)
